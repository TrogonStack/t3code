//! Regenerates `src/wire/generated.rs` from `packages/contracts/schema/rpc.schema.json` and fails
//! when the committed file differs. Run with `T3_UPDATE_GENERATED=1 cargo test --test wire_types`
//! to rewrite it. The schema is checked against the TypeScript contracts by
//! `vp run --filter @t3tools/contracts generate --check`.

use serde_json::{Map, Value};
use std::collections::BTreeSet;
use std::path::PathBuf;

/// RPC methods whose payload, success and error types are generated. Add a method here when the
/// client starts calling it.
const METHODS: &[&str] = &["orchestration.subscribeShell", "projects.mutate"];

/// Properties typify cannot represent, kept as `serde_json::Value`: (definition, property).
/// Gaps are listed in the README.
const OPAQUE: &[(&str, &str)] = &[("ProjectsEntry", "projectIcon")];

const HEADER: &str = "// @generated by `cargo test --test wire_types` from packages/contracts/schema/rpc.schema.json.\n// Do not edit. Regenerate with T3_UPDATE_GENERATED=1 cargo test --test wire_types.\n\n";

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn collect_refs(node: &Value, out: &mut BTreeSet<String>) {
    match node {
        Value::Object(map) => {
            for (key, value) in map {
                match (key.as_str(), value) {
                    ("$ref", Value::String(target)) => {
                        if let Some(name) = target.strip_prefix("#/$defs/") {
                            out.insert(name.to_owned());
                        }
                    }
                    _ => collect_refs(value, out),
                }
            }
        }
        Value::Array(items) => items.iter().for_each(|item| collect_refs(item, out)),
        _ => {}
    }
}

/// schemars 0.8 reads `#/definitions/`, draft 2020-12 writes `#/$defs/`.
fn retarget(node: &mut Value) {
    match node {
        Value::Object(map) => {
            for (key, value) in map.iter_mut() {
                if key == "$ref" {
                    if let Value::String(target) = value
                        && let Some(name) = target.strip_prefix("#/$defs/")
                    {
                        *target = format!("#/definitions/{name}");
                    }
                } else {
                    retarget(value);
                }
            }
        }
        Value::Array(items) => items.iter_mut().for_each(retarget),
        _ => {}
    }
}

fn subset() -> Value {
    let path = manifest_dir().join("../../packages/contracts/schema/rpc.schema.json");
    let document: Value =
        serde_json::from_str(&std::fs::read_to_string(&path).expect("read rpc.schema.json"))
            .expect("parse rpc.schema.json");
    let all = document["$defs"].as_object().expect("$defs");
    let mut pending: Vec<String> = Vec::new();
    for method in METHODS {
        let entry = &document["methods"][*method];
        for part in ["payload", "success", "error"] {
            let target = entry[part]["$ref"]
                .as_str()
                .unwrap_or_else(|| panic!("{method} {part} is not a $ref in the schema index"));
            pending.push(target.trim_start_matches("#/$defs/").to_owned());
        }
    }
    let mut needed = BTreeSet::new();
    while let Some(name) = pending.pop() {
        if needed.insert(name.clone()) {
            let mut refs = BTreeSet::new();
            collect_refs(&all[&name], &mut refs);
            pending.extend(refs);
        }
    }
    let definitions: Map<String, Value> = needed
        .into_iter()
        .map(|name| {
            let mut body = all[&name].clone();
            for (def, property) in OPAQUE {
                if *def == name {
                    body["properties"][*property] = serde_json::json!({});
                }
            }
            retarget(&mut body);
            (name, body)
        })
        .collect();
    serde_json::json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "WireRoot",
        "definitions": definitions,
    })
}

fn generate() -> String {
    let root: schemars::schema::RootSchema =
        serde_json::from_value(subset()).expect("schema subset is valid JSON Schema");
    let mut space = typify::TypeSpace::new(&typify::TypeSpaceSettings::default());
    space
        .add_root_schema(root)
        .expect("typify accepts the schema subset");
    let tokens = space.to_stream().expect("typify emits tokens");
    let file = syn::parse2(tokens).expect("generated code parses");
    format!("{HEADER}{}", prettyplease::unparse(&file))
}

#[test]
fn generated_wire_types_match_the_schema() {
    let path = manifest_dir().join("src/wire/generated.rs");
    let fresh = generate();
    if std::env::var_os("T3_UPDATE_GENERATED").is_some() {
        std::fs::write(&path, &fresh).expect("write generated.rs");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == fresh,
        "src/wire/generated.rs is stale. Run T3_UPDATE_GENERATED=1 cargo test --test wire_types"
    );
}
